/**
 * Groovy body of the AWS SigV4 JSR223 PreProcessor. Mirrors the reference signer in tests/helpers/awsSigV4/awsSigV4Signer.ts step by step.
 * Must never contain "${" — JMeter would substitute it before Groovy runs.
 */

export interface SigV4GroovyParams {
  region: string
  service: string
  accessKeyVar: string
  secretKeyVar: string
  sessionTokenVar: string
  signPayloadHeader: boolean
}

export function renderSigV4Groovy(p: SigV4GroovyParams): string {
  return String.raw`// AWS Signature Version 4 (HMAC-SHA256) — generated by JMeter Studio Auth Wizard.
// Keys are read at runtime from JMeter variables, -J properties or environment variables.
// Never paste real keys into this script.
import java.security.MessageDigest
import javax.crypto.Mac
import javax.crypto.spec.SecretKeySpec
import java.time.ZonedDateTime
import java.time.ZoneOffset
import java.time.format.DateTimeFormatter
import org.apache.jmeter.protocol.http.control.Header
import org.apache.jmeter.protocol.http.control.HeaderManager
import org.apache.jmeter.protocol.http.sampler.HTTPSamplerBase
import org.apache.jmeter.testelement.property.TestElementProperty

String REGION = '${p.region}'
String SERVICE = '${p.service}'
boolean SIGN_PAYLOAD_HEADER = ${p.signPayloadHeader ? 'true' : 'false'}
def setting = { String name -> name ? (vars.get(name) ?: props.getProperty(name) ?: System.getenv(name)) : null }
String accessKey = setting('${p.accessKeyVar}')
String secretKey = setting('${p.secretKeyVar}')
String sessionToken = setting('${p.sessionTokenVar}')
if (!accessKey || !secretKey) {
  log.error('AWS SigV4: define ${p.accessKeyVar} and ${p.secretKeyVar} (JMeter variable, -J property or environment variable)')
  return
}

def hex = { byte[] bytes -> bytes.encodeHex().toString() }
def sha256 = { String text -> hex(MessageDigest.getInstance('SHA-256').digest(text.getBytes('UTF-8'))) }
def hmac = { byte[] key, String data ->
  Mac mac = Mac.getInstance('HmacSHA256')
  mac.init(new SecretKeySpec(key, 'HmacSHA256'))
  mac.doFinal(data.getBytes('UTF-8'))
}
def enc = { String text -> URLEncoder.encode(text, 'UTF-8').replace('+', '%20').replace('*', '%2A').replace('%7E', '~') }
def pathDec = { String text -> try { URLDecoder.decode(text.replace('+', '%2B'), 'UTF-8') } catch (ignored) { text } }
def queryDec = { String text -> try { URLDecoder.decode(text, 'UTF-8') } catch (ignored) { text } }

URL url = sampler.getUrl()
String method = sampler.getMethod().toUpperCase()
def args = sampler.getArguments()
String body = ''
if (sampler.getPostBodyRaw()) {
  body = (0..<args.getArgumentCount()).collect { args.getArgument(it).getValue() }.join('')
} else if (!['GET', 'HEAD', 'DELETE', 'OPTIONS'].contains(method)) {
  body = sampler.getQueryString()
}

String rawPath = url.getPath()
String rawQuery = url.getQuery()
try {
  URI uri = url.toURI()
  rawPath = uri.getRawPath()
  rawQuery = uri.getRawQuery()
} catch (ignored) { }
rawPath = rawPath ?: '/'
String canonicalPath = rawPath.split('/', -1).collect { seg ->
  String once = enc(pathDec(seg))
  SERVICE == 's3' ? once : enc(once)
}.join('/')
String canonicalQuery = !rawQuery ? '' : rawQuery.split('&').findAll { it }.collect { pair ->
  int i = pair.indexOf('=')
  [enc(queryDec(i < 0 ? pair : pair.substring(0, i))), enc(queryDec(i < 0 ? '' : pair.substring(i + 1)))]
}.sort { a, b -> (a[0] <=> b[0]) ?: (a[1] <=> b[1]) }.collect { it[0] + '=' + it[1] }.join('&')

String amzDate = ZonedDateTime.now(ZoneOffset.UTC).format(DateTimeFormatter.ofPattern("yyyyMMdd'T'HHmmss'Z'"))
String dateStamp = amzDate.substring(0, 8)
int port = url.getPort()
String host = url.getHost() + (port != -1 && port != url.getDefaultPort() ? ':' + port : '')
String payloadHash = sha256(body)

def signed = new TreeMap<String, String>()
signed.put('host', host)
signed.put('x-amz-date', amzDate)
if (SIGN_PAYLOAD_HEADER) signed.put('x-amz-content-sha256', payloadHash)
if (sessionToken) signed.put('x-amz-security-token', sessionToken)
String signedHeaders = signed.keySet().join(';')
String canonicalHeaders = signed.collect { k, v -> k + ':' + v.trim() + '\n' }.join('')
String canonicalRequest = [method, canonicalPath, canonicalQuery, canonicalHeaders, signedHeaders, payloadHash].join('\n')
String scope = dateStamp + '/' + REGION + '/' + SERVICE + '/aws4_request'
String stringToSign = ['AWS4-HMAC-SHA256', amzDate, scope, sha256(canonicalRequest)].join('\n')
byte[] signingKey = hmac(hmac(hmac(hmac(('AWS4' + secretKey).getBytes('UTF-8'), dateStamp), REGION), SERVICE), 'aws4_request')
String signature = hex(hmac(signingKey, stringToSign))
String authorization = 'AWS4-HMAC-SHA256 Credential=' + accessKey + '/' + scope + ', SignedHeaders=' + signedHeaders + ', Signature=' + signature

// Per-sample copy: the sampler's HeaderManager can be shared with other samplers in the same scope,
// so never mutate it. The property set here is reverted by JMeter after the sample (running version),
// so headers never accumulate across iterations.
HeaderManager shared = sampler.getHeaderManager()
HeaderManager manager = shared != null ? (HeaderManager) shared.clone() : new HeaderManager()
['Authorization', 'X-Amz-Date', 'X-Amz-Content-Sha256', 'X-Amz-Security-Token'].each { manager.removeHeaderNamed(it) }
manager.add(new Header('Authorization', authorization))
manager.add(new Header('X-Amz-Date', amzDate))
if (SIGN_PAYLOAD_HEADER) manager.add(new Header('X-Amz-Content-Sha256', payloadHash))
if (sessionToken) manager.add(new Header('X-Amz-Security-Token', sessionToken))
sampler.setProperty(new TestElementProperty(HTTPSamplerBase.HEADER_MANAGER, manager))
vars.put('AWS_SIGV4_AUTHORIZATION', authorization)
`
}
